controls.zoomSpeed = 0.7

// Collision uses an invisible proxy mesh generated by splat-transform.
const COLLISION_LAYER = 1
const PLAYER_RADIUS = 0.25
const PLAYER_HEIGHT = 1.6
const collisionRaycaster = new THREE.Raycaster()
collisionRaycaster.layers.set(COLLISION_LAYER)
const collisionState = {
  root: null,
  ready: false
}
const collisionOrigin = new THREE.Vector3()
const collisionDirection = new THREE.Vector3()
const gltfLoader = new GLTFLoader()

const desktopMoveState = {
  forward: false,
  back: false,
  left: false,
  right: false
}
const desktopMoveSpeed = 0.06

const splatManager = new SplatManager({
  scene,
  renderer,
  camera,
  maxBytes: MAX_SPLAT_BYTES,
  allowPly: true,
  renderOrder: 2,
  disableDepthTest: true
})

function setLoading(isLoading, text = 'Loading splat...') {
  loadingEl.textContent = text
  loadingEl.classList.toggle('hidden', !isLoading)
}

function loadCollisionMesh() {
  return new Promise((resolve) => {
    gltfLoader.load(
      COLLISION_URL,
      (gltf) => {
        const root = gltf.scene
        let meshCount = 0
        root.traverse((child) => {
          child.layers.set(COLLISION_LAYER)
          if (child.isMesh) {
            meshCount += 1
            if (Array.isArray(child.material)) {
              child.material = child.material.map((material) => {
                const clone = material?.clone?.()
                const target = clone ?? material
                if (target) {
                  target.visible = false
                  target.side = THREE.DoubleSide
                }
                return target
              })
            } else if (child.material?.clone) {
              child.material = child.material.clone()
              child.material.visible = false
              child.material.side = THREE.DoubleSide
            } else if (child.material) {
              child.material.visible = false
              child.material.side = THREE.DoubleSide
            }
            child.castShadow = false
            child.receiveShadow = false
          }
        })
        root.layers.set(COLLISION_LAYER)
        scene.add(root)
        collisionState.root = root
        collisionState.ready = true
        console.log(`[Collision] Collider cargado con ${meshCount} meshes`)
        resolve(root)
      },
      undefined,
      (error) => {
        console.warn('[Collision] No se pudo cargar el collider:', error)
        collisionState.root = null
        collisionState.ready = false
        resolve(null)
      }
    )
  })
}

function alignCollisionToSplat() {
  const viewer = splatManager.getViewer()
  const splatMesh = viewer?.splatMesh
  if (!collisionState.root || !splatMesh) return

  splatMesh.updateMatrixWorld(true)
  splatMesh.matrixWorld.decompose(
    collisionState.root.position,
    collisionState.root.quaternion,
    collisionState.root.scale
  )
  collisionState.root.updateMatrixWorld(true)
}

function applyCollisionToVelocity(desiredVelocity) {
  if (!collisionState.ready || !collisionState.root) {
    return desiredVelocity
  }

  collisionDirection.set(desiredVelocity.x, 0, desiredVelocity.z)
  const distance = collisionDirection.length()
  if (distance === 0) return desiredVelocity

  collisionDirection.normalize()
  collisionOrigin.set(
    cameraGroup.position.x,
    cameraGroup.position.y + PLAYER_HEIGHT * 0.5,
    cameraGroup.position.z
  )

  collisionRaycaster.set(collisionOrigin, collisionDirection)
  collisionRaycaster.far = distance + PLAYER_RADIUS

  const hits = collisionRaycaster.intersectObject(collisionState.root, true)
  if (hits.length && hits[0].distance <= distance + PLAYER_RADIUS) {
    desiredVelocity.x = 0
    desiredVelocity.z = 0
  }

  return desiredVelocity
}

async function loadInitialSplat() {
  setLoading(true)
  try {
    // Calcular la rotación usando Euler para facilitar el ajuste.
    // Ej: -90 en X la levanta (si estaba acostada), 180 en Y la gira hacia ti.
    //const euler = new THREE.Euler(
    //  THREE.MathUtils.degToRad(-10), // Rotación X
    //  THREE.MathUtils.degToRad(185), // Rotación Y
    //  THREE.MathUtils.degToRad(179),   // Rotación Z
    //  'XYZ'
    //);
    const euler = new THREE.Euler(
      THREE.MathUtils.degToRad(10), // Rotación X
      THREE.MathUtils.degToRad(50), // Rotación Y
      THREE.MathUtils.degToRad(180),   // Rotación Z
      'XYZ'
    );
    const quat = new THREE.Quaternion().setFromEuler(euler);

    await splatManager.load(MODEL_URL, {
      onProgress: (progress) => {
        if (typeof progress === 'number') {
          const percent = Math.round(progress * 100)
          setLoading(true, `Loading splat... ${percent}%`)
        }
      },
      transform: {
        position: [0, 0, -3], // Posicionado a 3 metros al frente de la cámara
        rotation: [quat.x, quat.y, quat.z, quat.w], 
        scale: [1, 1, 1]
      }
    })
    if (!collisionState.ready) {
      await loadCollisionMesh()
    }
    alignCollisionToSplat()
    controls.update()
    setLoading(false)
  } catch (error) {
    console.error(error)
    setLoading(true, error.message || 'Failed to load splat')
  }
}

function updateRendererSize() {
  camera.aspect = window.innerWidth / window.innerHeight
  camera.updateProjectionMatrix()
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.5))
  renderer.setSize(window.innerWidth, window.innerHeight, false)
}

async function enterVR() {
  if (!navigator.xr) {
    alert('WebXR not available in this browser')
    return
  }

  enterVrButton.disabled = true

  try {
    const session = await navigator.xr.requestSession('immersive-vr', {
      optionalFeatures: ['local-floor']
    })
    renderer.xr.setSession(session)

    session.addEventListener('end', () => {
      enterVrButton.disabled = false
    })
  } catch (error) {
    console.error(error)
    enterVrButton.disabled = false
  }
}

